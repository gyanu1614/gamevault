/** Legacy alias — a quiet centered line. Prefer emailFooterNote for closers. */
export function emailSubtle(html: string): string {
  return `<p class="dm-muted" style="font-size:12px;line-height:1.6;color:${MUTED};text-align:center;margin:12px 0 0;">${html}</p>`
}

/** Legacy label:value row (left label / right value). */
export function emailRow(label: string, value: string): string {
  return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin:0 0 8px;"><tr>
    <td class="dm-body" style="font-family:${FONT};font-size:14px;color:${INK_2};">${label}</td>
    <td class="dm-strong" style="font-family:${FONT};font-size:14px;font-weight:600;color:${INK};text-align:right;">${value}</td>
  </tr></table>`
}

/** Legacy order-summary box from [label,value] rows; last row can be emphasised. */
export function emailOrderSummary(rows: Array<[string, string]>, highlightLast = false): string {
  const inner = rows
    .map(([label, value], i) => {
      const emph = highlightLast && i === rows.length - 1
      const top = emph ? `border-top:1px solid ${LINE};padding-top:10px;` : ''
      const ls = emph ? `font-size:15px;font-weight:700;color:${FOREST_2};` : `font-size:14px;color:${INK_2};`
      const vs = emph ? `font-size:16px;font-weight:800;color:${FOREST_2};` : `font-size:14px;font-weight:600;color:${INK};`
      return `<tr>
        <td class="dm-body" style="font-family:${FONT};${ls}${top}padding-bottom:8px;">${label}</td>
        <td class="${emph ? 'dm-accent' : 'dm-strong'}" style="font-family:${FONT};${vs}${top}padding-bottom:8px;text-align:right;overflow-wrap:anywhere;">${value}</td>
      </tr>`
    })
    .join('')
  return emailBox({ html: `<table role="presentation" width="100%" cellpadding="0" cellspacing="0">${inner}</table>` })
}

